package com.wengu.source.entity;

/** 材料类型，按名称存进 source.type。截图识别出的文字按粘贴的原文处理，没有单独的类型（决策 044）。 */
public enum SourceType {
    /** 题目清单：面试题文本、题库。模型从原文中逐字找出题目（决策 011） */
    QUESTION,
    /** 讲解资料：笔记、技术文章、书的章节。原文中没有现成的题目，由模型根据内容整理出题目（#26，决策 037） */
    DOCUMENT,
    /** 源码：用户勾选的项目文件，存在 source_file 表；没有题目，直接从代码抽取个人经历类知识点（#90，决策 050） */
    CODE
}
